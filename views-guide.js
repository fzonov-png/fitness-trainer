function renderDayPlan(kind) {
  const plan = MEAL_KINDS[kind];
  return (
    '<h3>' + esc(plan.label) + '</h3>' +
    '<p class="hint">' + esc(plan.lead) + '</p>' +
    '<table class="meals">' +
      plan.meals.map((m) => '<tr><td>' + esc(m[0]) + '</td><td>' + esc(m[1]) + '</td><td>' + esc(m[2]) + '</td></tr>').join('') +
    '</table>'
  );
}

