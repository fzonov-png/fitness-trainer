function renderLibrary() {
  const groups = ['Собственный вес', 'Гребля', 'Гиря', 'Гантели', 'Турник', 'Кор', 'Мобильность', 'Растяжка', 'Дыхание'];
  const byGroup = {};
  Object.keys(P.EX).forEach((id) => {
    const ex = P.EX[id];
    const g = ex.group || 'Другое';
    byGroup[g] = byGroup[g] || [];
    byGroup[g].push({ id: id, ex: ex });
  });
  let html = '<div id="library"><div class="libsearch"><input id="lib-search" type="search" placeholder="Найти упражнение: шпагат, мах, жим…" aria-label="Поиск упражнения"></div>';
  groups.forEach((g) => {
    if (!byGroup[g]) return;
    html += '<div class="lib-group"><h3>' + g + '</h3>';
    byGroup[g].forEach((x) => {
      const cues = (x.ex.cues || []).map((c) => '<li>' + esc(c) + '</li>').join('');
      const mistakes = (x.ex.mistakes || []).map((c) => '<li>' + esc(c) + '</li>').join('');
      html +=
        '<details class="lib">' +
          '<summary>' + esc(x.ex.name) + (x.ex.eq ? '<span>' + esc(x.ex.eq) + '</span>' : '') + '</summary>' +
          '<div class="lib__body">' +
            (x.ex.target ? '<p class="lib__target">' + esc(x.ex.target) + '</p>' : '') +
            (cues ? '<ul>' + cues + '</ul>' : '') +
            (mistakes ? '<p class="lib__bad">Ошибки: ' + esc(x.ex.mistakes.join('; ')) + '</p>' : '') +
            '<div class="lib__alt">' + (x.ex.easier ? '<span>Проще: ' + esc(x.ex.easier) + '</span>' : '') + (x.ex.harder ? '<span>Сложнее: ' + esc(x.ex.harder) + '</span>' : '') + '</div>' +
          '</div>' +
        '</details>';
    });
    html += '</div>';
  });
  return html + '</div>';
}

